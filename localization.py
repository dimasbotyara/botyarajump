def get_text(key, language=None):
    """Get localized text by key."""
    if language is None:
        from settings import save_manager
        language = save_manager.get_language()

    if key in TEXTS:
        return TEXTS[key].get(language, TEXTS[key].get("en", key))
    return key


def get_key_display_name(key_name):
    """Convert pygame key constant name to display name."""
    if not key_name or key_name == "":
        return "---"

    # Remove K_ prefix
    name = key_name.replace("K_", "")

    # Special names
    special = {
        "LEFT": "←",
        "RIGHT": "→",
        "UP": "↑",
        "DOWN": "↓",
        "SPACE": "Space",
        "RETURN": "Enter",
        "ESCAPE": "Esc",
        "LSHIFT": "L.Shift",
        "RSHIFT": "R.Shift",
        "LCTRL": "L.Ctrl",
        "RCTRL": "R.Ctrl",
        "LALT": "L.Alt",
        "RALT": "R.Alt",
        "TAB": "Tab",
        "BACKSPACE": "Backspace"
    }

    if name in special:
        return special[name]

    return name.upper()